// 'in terms of π' 문항인데 보기에 π 없는 값이 섞인 공개 SAT 문항(Test 1~26 현재 공개 버전)을 전수 찾아 보기를 전부 π 형식으로 바꾸는 새 problem_version 패치 SQL.
//   npx tsx scripts/prod-open/sat-pi-patches-sql.ts [--out data/prod-open/sat-expand-sql]
//   산출: 10_pi_options_patches.sql · 99_pi_rollback.sql(=10 롤백) · 10_preflight.sql · 10_verify.sql · 10_pi_options_patches.report.json
// 정답 값·정답 위치 유지(π 없는 오답에만 π 를 붙이고, 정답/다른 보기와 겹치면 2배·4배·1/2배 값으로 대체). 원격은 읽기 SELECT 만.
import { spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { planPatch, type Patch, type PatchPlan, type ProblemReadout } from "../../lib/audit-fix/plan";
import { emitApplySql, emitRollbackSql, toSqlPlan } from "../../lib/audit-fix/sql";
import { PROBLEM_SELECT } from "../audit/apply-audit-fixes";

const arg = (n: string) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : undefined; };
const OUT = path.resolve(arg("--out") ?? "data/prod-open/sat-expand-sql");
function dbRows<T = any>(sql: string): T[] {
  const r = spawnSync("supabase", ["db", "query", "--linked", sql], { encoding: "utf-8", maxBuffer: 512 * 1024 * 1024 });
  if (r.status !== 0) throw new Error(`supabase db query 실패: ${(r.stderr || r.stdout).slice(0, 400)}`);
  const o = r.stdout; return (JSON.parse(o.slice(o.indexOf("{"), o.lastIndexOf("}") + 1)) as { rows: T[] }).rows;
}

export const hasPi = (t: string) => /π|\\pi/.test(t);
export const isPiQuestion = (q: string, p: string) => /in terms of (\$?\\?pi\$?|π)/i.test(`${q} ${p}`);
/** 보기에 π 있는/없는 값이 섞였으면 모두 π 형식으로 바꾼 새 보기를, 아니면 null. */
export function piOptions(options: string[]): string[] | null {
  const n = options.filter(hasPi).length;
  if (n === 0 || n === options.length) return null;
  const used = new Set(options.filter(hasPi).map((o) => o.trim()));
  const out: string[] = [];
  for (const o of options) {
    if (hasPi(o)) { out.push(o); continue; }
    const x = Number(o.replace(/[$,\s]/g, ""));
    if (!Number.isFinite(x)) return null;
    const fmt = (v: number) => `${Number.isInteger(v) ? v : String(v)}π`;
    const cand = [x, 2 * x, 4 * x, x / 2].map(fmt).find((c) => !used.has(c));
    if (!cand) return null;
    used.add(cand); out.push(cand);
  }
  return out;
}

if (process.argv[1]?.endsWith("sat-pi-patches-sql.ts")) {
  const rows = dbRows<{ problem_id: string; set_name: string; question: string | null; passage: string | null; options: string[] | null }>(`select distinct on (p.id, s.name) p.id as problem_id, s.name as set_name, pv.question, pv.passage, pv.options
    from mock_exam_sets s join mock_exam_set_items i on i.exam_set_id = s.id join problems p on p.id = i.problem_id join problem_versions pv on pv.id = p.published_version_id
    where s.name ~ '^SAT Practice Test [0-9]+$' and s.archived_at is null and s.status = 'published' and pv.options is not null order by p.id, s.name`);
  const targets = new Map<string, { sets: string[]; options: string[]; next: string[] }>();
  for (const r of rows) {
    if (!isPiQuestion(r.question ?? "", r.passage ?? "")) continue;
    const next = piOptions(r.options!);
    if (!next) continue;
    const t = targets.get(r.problem_id) ?? { sets: [], options: r.options!, next };
    t.sets.push(r.set_name.replace("SAT Practice Test ", "T")); targets.set(r.problem_id, t);
  }
  const ids = [...targets.keys()];
  const readouts = ids.length ? dbRows<ProblemReadout>(PROBLEM_SELECT(`p.id = any (array[${ids.map((i) => `'${i}'`).join(",")}]::uuid[])`)) : [];
  const plans: PatchPlan[] = [];
  const items: unknown[] = [];
  ids.forEach((pid, i) => {
    const id = `E1019-P${String(i + 1).padStart(3, "0")}`; const t = targets.get(pid)!; const r = readouts.find((x) => x.problem_id === pid)!;
    const p: Patch = { id, problemId: pid, expectVersionId: r.published_version_id ?? undefined, kind: "sat", why: "'in terms of π' 문항: 보기를 전부 π 형식으로(정답 값·위치 유지)", changes: [{ field: "options", old: t.options, new: t.next }] };
    const already = (r.pub?.quality as any)?.auditFix?.patch === id;
    plans.push(already ? ({ ...planPatch({ ...p, expectVersionId: undefined }, r), status: "already" } as PatchPlan) : planPatch(p, r));
    items.push({ patch: id, problemId: pid, sets: t.sets, old: t.options, new: t.next, correctIndex: r.pub?.correct_index });
  });
  const tally: Record<string, number> = {}; for (const p of plans) tally[p.status] = (tally[p.status] ?? 0) + 1;
  console.log("targets", ids.length, tally);
  for (const p of plans) if (p.status !== "apply" && p.status !== "already") console.log(p.patchId, p.status, p.reasons.join("|").slice(0, 300));
  if (plans.some((p) => p.status !== "apply" && p.status !== "already")) process.exit(1);
  const sqlPlan = toSqlPlan(plans, [], "scripts/prod-open/sat-pi-patches-sql.ts");
  const HDR = (w: string) => `-- ${w}\n-- generated by scripts/prod-open/sat-pi-patches-sql.ts. Run: npx supabase db query --linked -f <this file>. Idempotent; new problem_versions only; no deletes/overwrites; set composition untouched.\n`;
  const idList = `array[${ids.map((i) => `'${i}'`).join(",")}]::uuid[]`;
  mkdirSync(OUT, { recursive: true });
  writeFileSync(path.join(OUT, "10_pi_options_patches.sql"), emitApplySql(sqlPlan).replace("External audit fixes 2026-10-13 - APPLY", "SAT 'in terms of pi' option-format patches 2026-10-19 - new problem versions (no set changes)"));
  writeFileSync(path.join(OUT, "99_pi_rollback.sql"), emitRollbackSql(sqlPlan, []));
  writeFileSync(path.join(OUT, "10_preflight.sql"), `${HDR("preflight for 10 (SELECT only)")}
select p.id as problem_id, pv.version_no, pv.options, pv.correct_index, (select count(*) from problem_versions v where v.problem_id = p.id and v.status in ('draft', 'in_review')) as inflight_versions,
  (select string_agg(distinct s.name || ' (' || s.status || ')', ', ') from mock_exam_set_items i join mock_exam_sets s on s.id = i.exam_set_id where i.problem_id = p.id and s.status in ('published', 'draft')) as used_in
from problems p join problem_versions pv on pv.id = p.published_version_id where p.id = any (${idList}) order by p.id;
`);
  writeFileSync(path.join(OUT, "10_verify.sql"), `${HDR("verify after 10 (SELECT only): every option has the pi form, correct answer unchanged")}
select p.id as problem_id, pv.version_no, pv.quality->'auditFix'->>'patch' as patch, pv.options, pv.correct_index, pv.options->>pv.correct_index as correct_text,
  (select bool_and(o ~ 'π') from jsonb_array_elements_text(pv.options) o) as all_pi
from problems p join problem_versions pv on pv.id = p.published_version_id where p.id = any (${idList}) order by 3;
`);
  writeFileSync(path.join(OUT, "10_pi_options_patches.report.json"), JSON.stringify({ count: ids.length, tally, items }, null, 1));
  console.log(items.map((x: any) => `${x.patch} ${x.sets.join("/")} ${JSON.stringify(x.old)} -> ${JSON.stringify(x.new)}`).join("\n"));
}
