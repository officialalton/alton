// SAT 신규 세트(lit25) 지문 160단어 초과 10건 단축 SQL 생성기(백로그 A4, 2026-10-19). 계획: data/audit/sat-trim160-plan-20261019.json(`sat-trim160-plan.ts`).
//   npx tsx scripts/prod-open/sat-trim160-sql.ts [--out data/prod-open/sat-expand-sql]
//   산출: 25_trim160.sql · 99_trim160_rollback.sql · 25_preflight.sql · 25_verify.sql · 25_trim160.report.json  (세트 새 버전은 `SAT_26=1 npx tsx scripts/prod-open/sat-expand-sql.ts` → 26_*)
// 원격은 읽기 SELECT 만(문항은 mockExamGeneration.gid 로 찾는다). 새 problem_versions 만 만들며 삭제·덮어쓰기 없음, 멱등(이미 같은 지문이면 건너뜀, 기대한 옛 지문과 다르면 전체 롤백).
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { planPatch, type Patch, type PatchChange, type PatchPlan, type ProblemReadout } from "../../lib/audit-fix/plan";
import { emitApplySql, emitRollbackSql, toSqlPlan } from "../../lib/audit-fix/sql";
import { PROBLEM_SELECT } from "../audit/apply-audit-fixes";

const ROOT = path.resolve(__dirname, "../..");
const arg = (n: string) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : undefined; };
const OUT = path.resolve(arg("--out") ?? "data/prod-open/sat-expand-sql");
function dbRows<T = any>(sql: string): T[] {
  const r = spawnSync("supabase", ["db", "query", "--linked", sql], { encoding: "utf-8", maxBuffer: 512 * 1024 * 1024 });
  if (r.status !== 0) throw new Error(`supabase db query 실패: ${(r.stderr || r.stdout).slice(0, 400)}`);
  const o = r.stdout; return (JSON.parse(o.slice(o.indexOf("{"), o.lastIndexOf("}") + 1)) as { rows: T[] }).rows;
}
type PlanItem = { gid: string; passage_old: string; passage_new: string; words_before: number; words_after: number; note: string; explanation_en_edit?: [string, string]; explanation_edit?: [string, string]; problems: string[] };
const plan = JSON.parse(fs.readFileSync(path.join(ROOT, "data/audit/sat-trim160-plan-20261019.json"), "utf8")) as { items: PlanItem[] };
if (plan.items.some((i) => i.problems.length)) { console.error("계획에 미해결 문제가 있음 — sat-trim160-plan.ts 먼저"); process.exit(1); }
const gids = plan.items.map((i) => i.gid);
const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const readouts = dbRows<ProblemReadout>(PROBLEM_SELECT(`p.id in (select pv.problem_id from problem_versions pv where pv.quality->'mockExamGeneration'->>'gid' = any (array[${gids.map(lit).join(",")}]))`));
const plans: PatchPlan[] = []; const items: unknown[] = [];
plan.items.forEach((it, i) => {
  const r = readouts.find((x) => x.gid === it.gid);
  if (!r?.pub) throw new Error(`${it.gid}: DB 에서 공개 버전을 찾지 못함`);
  const cur = r.pub;
  if ((cur.passage ?? "") !== it.passage_old) throw new Error(`${it.gid}: DB 지문이 계획의 원문과 다름(이미 바뀌었거나 다른 버전) — 계획을 다시 만드세요`);
  const id = `E1019-T${String(i + 1).padStart(3, "0")}`;
  const changes: PatchChange[] = [{ field: "passage", old: cur.passage, new: it.passage_new }];
  for (const [field, edit] of [["explanation_en", it.explanation_en_edit], ["explanation", it.explanation_edit]] as const) {
    if (!edit) continue;
    const old = (cur as any)[field] as string;
    if (old.split(edit[0]).length !== 2) throw new Error(`${it.gid}: ${field} 에서 수정할 문장을 정확히 한 번 찾지 못함`);
    changes.push({ field, old, new: old.replace(edit[0], edit[1]) });
  }
  const p: Patch = { id, problemId: r.problem_id, expectVersionId: r.published_version_id ?? undefined, kind: "sat", why: `지문 160단어 초과 단축(${it.words_before}→${it.words_after}단어, 삭제만): ${it.note}`, changes };
  const already = (cur.quality as any)?.auditFix?.patch === id;
  plans.push(already ? ({ ...planPatch({ ...p, expectVersionId: undefined }, r), status: "already" } as PatchPlan) : planPatch(p, r));
  items.push({ patch: id, gid: it.gid, problemId: r.problem_id, words: `${it.words_before}->${it.words_after}`, fields: changes.map((c) => c.field), usedIn: (r.placements ?? []).filter((x) => x.set_status === "published").map((x) => `${x.set_name} v${x.set_version} ${x.section}#${x.position}`) });
});
const tally: Record<string, number> = {}; for (const p of plans) tally[p.status] = (tally[p.status] ?? 0) + 1;
console.log("plan status:", tally);
for (const p of plans) { if (p.status !== "apply" && p.status !== "already") console.log(`  ${p.patchId} ${p.status}: ${p.reasons.join(" | ").slice(0, 400)}`); for (const w of p.warnings) console.log(`  warn ${p.patchId}: ${w.slice(0, 200)}`); }
if (plans.some((p) => p.status !== "apply" && p.status !== "already")) { console.error("계획 실패 — 파일을 쓰지 않고 중단"); process.exit(1); }

const sqlPlan = toSqlPlan(plans, [], "scripts/prod-open/sat-trim160-sql.ts");
const HDR = (w: string) => `-- ${w}\n-- generated by scripts/prod-open/sat-trim160-sql.ts. Run: npx supabase db query --linked -f <this file>. Idempotent; new problem_versions only; no deletes/overwrites; set composition untouched.\n`;
const ids = plans.map((p) => p.problemId!);
const idList = `array[${ids.map((i) => `'${i}'`).join(",")}]::uuid[]`;
fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, "25_trim160.sql"), emitApplySql(sqlPlan).replace("External audit fixes 2026-10-13 - APPLY", "SAT lit25 passages over 160 words - deletion-only trims 2026-10-19 (E1019-T*) - new problem versions (no set changes)"));
fs.writeFileSync(path.join(OUT, "99_trim160_rollback.sql"), emitRollbackSql(sqlPlan, []));
fs.writeFileSync(path.join(OUT, "25_preflight.sql"), `${HDR("preflight for 25 (SELECT only): the 10 lit25 passages over 160 words - current published version, word count, in-flight drafts, set usage")}
select p.id as problem_id, pv.quality->'mockExamGeneration'->>'gid' as gid, pv.version_no, pv.quality->'auditFix'->>'patch' as patch,
  cardinality(regexp_split_to_array(trim(pv.passage), '\\s+')) as words,
  (select count(*) from problem_versions v where v.problem_id = p.id and v.status in ('draft', 'in_review')) as inflight_versions,
  (select string_agg(distinct s.name || ' v' || s.version_no || ' (' || s.status || ')', ', ') from mock_exam_set_items i join mock_exam_sets s on s.id = i.exam_set_id where i.problem_id = p.id and s.status in ('published', 'draft')) as used_in
from problems p join problem_versions pv on pv.id = p.published_version_id where p.id = any (${idList}) order by 2;
`);
fs.writeFileSync(path.join(OUT, "25_verify.sql"), `${HDR("verify after 25 (SELECT only): every trimmed passage is <= 160 words and on an E1019-T* version")}
select p.id as problem_id, pv.quality->'mockExamGeneration'->>'gid' as gid, pv.version_no, pv.quality->'auditFix'->>'patch' as patch, cardinality(regexp_split_to_array(trim(pv.passage), '\\s+')) as words,
  cardinality(regexp_split_to_array(trim(pv.passage), '\\s+')) <= 160 as within_160
from problems p join problem_versions pv on pv.id = p.published_version_id where p.id = any (${idList}) order by 2;
`);
fs.writeFileSync(path.join(OUT, "25_trim160.report.json"), JSON.stringify({ count: plans.length, tally, items }, null, 1));
console.log("wrote 25_trim160.sql, 99_trim160_rollback.sql, 25_preflight.sql, 25_verify.sql, 25_trim160.report.json");
