// 계획 → 실행 SQL(한 개의 DO 블록 = 한 트랜잭션), 롤백 SQL, 검증 SELECT. 순수 문자열 생성(골든 테스트 대상).
// 쓰는 길은 기존 문제은행·세트 흐름 그대로다: save_problem_draft_version → set_problem_render_check → set_problem_quality → confirm_and_publish_problem_version(→ AP: ap_attach_new_version),
// 세트는 mock_exam_create_new_version / mock_exam_refresh_explanations 와 같은 복사 방식(카탈로그 컬럼 목록)으로 version_no+1 초안 → 검증 → mock_exam_publish_set(이전 공개본 보관 + 공개 범위 승계).
// 응시·답안·결과·옛 공개본(보관됨)은 읽기만 한다. 총괄이 `supabase db query --linked -f <file>` 로 실행(서브에이전트는 쓰지 않는다).
import type { PatchPlan, SetPlan } from "./plan";

export const PLAN_TAG = "audit_plan";
const jsonLit = (v: unknown) => {
  const s = JSON.stringify(v);
  if (s.includes(`$${PLAN_TAG}$`)) throw new Error("plan JSON contains the dollar-quote tag");
  return `$${PLAN_TAG}$${s}$${PLAN_TAG}$::jsonb`;
};

/** expect = 바뀌는 필드의 DB 현재(옛) 값, set = 그 필드의 새 값(+정규화된 그림·figure_checked). 나머지 필드는 SQL 이 현재 공개 버전에서 복사한다(계획 크기를 줄이고 드리프트에 안전). */
export type ProblemUnit = { patch_id: string; problem_id: string; from_version_id: string; expect: Record<string, unknown>; set: Record<string, unknown>; render_check: unknown; audit_fix: unknown; ap?: { candidate_key: string; item_index: number } };
export type SqlPlan = { generatedBy: string; problems: ProblemUnit[]; sets: { set_group_id: string; set_id: string; name: string; version_no: number; format: string; problem_ids: string[]; patch_ids: string[] }[] };

export function toSqlPlan(plans: PatchPlan[], sets: SetPlan[], generatedBy = "scripts/audit/apply-audit-fixes.ts"): SqlPlan {
  const problems: ProblemUnit[] = plans.filter((p) => p.status === "apply" && p.args && p.problemId && p.fromVersionId).map((p) => ({
    patch_id: p.patchId, problem_id: p.problemId!, from_version_id: p.fromVersionId!, expect: p.expect, set: p.set, render_check: p.renderCheck, audit_fix: p.auditFix, ...(p.ap ? { ap: p.ap } : {}),
  }));
  return { generatedBy, problems, sets: sets.map((s) => ({ set_group_id: s.setGroupId, set_id: s.setId, name: s.name, version_no: s.versionNo, format: s.format, problem_ids: s.problemIds, patch_ids: s.patchIds })) };
}

const HEADER = (what: string, plan: SqlPlan) => `-- ${what}
-- generated by ${plan.generatedBy}. Non-production target only (worpsqwqgnspddnrtnvq). One DO block = one transaction: any failure rolls everything back.
-- problems: ${plan.problems.length} new problem versions, sets: ${plan.sets.length} new set versions (draft -> validate -> publish; previous version archived; access tier inherited).
-- Run (coordinator): npx supabase db query --linked -f <this file>
`;

/** 실행 SQL. 멱등: 이미 반영된 문항·세트는 건너뛰고, 기대한 옛 값과 다르면 예외로 전체 롤백. */
export function emitApplySql(plan: SqlPlan): string {
  return `${HEADER("External audit fixes 2026-10-13 - APPLY", plan)}
do $audit$
declare
  v_plan constant jsonb := ${jsonLit(plan)};
  v_actor uuid := (select id from profiles where role = 'admin' order by created_at limit 1);
  u jsonb; s jsonb; a jsonb;
  v_prob problems%rowtype; v_cur problem_versions%rowtype; v_have jsonb; v_want jsonb; v_new uuid;
  v_src mock_exam_sets%rowtype; v_new_set uuid; v_cols text; v_cols_i text; v_pids uuid[];
  v_n int; v_stale int; v_bad text; v_done_p int := 0; v_skip_p int := 0; v_done_s int := 0; v_skip_s int := 0;
begin
  if v_actor is null then raise exception 'No admin profile found.'; end if;

  -- Phase 1: problems -> new published problem version each (same flow as the admin problem editor)
  for u in select * from jsonb_array_elements(v_plan->'problems') loop
    select * into v_prob from problems where id = (u->>'problem_id')::uuid;
    if v_prob.id is null then raise exception '[%] problem % not found', u->>'patch_id', u->>'problem_id'; end if;
    select * into v_cur from problem_versions where id = v_prob.published_version_id;
    if v_cur.id is null then raise exception '[%] problem % has no published version', u->>'patch_id', v_prob.id; end if;
    -- final field values = current published version, overridden by the planned new values
    a := jsonb_build_object('passage', v_cur.passage, 'question', v_cur.question, 'options', v_cur.options, 'correct_index', v_cur.correct_index, 'answers', v_cur.answers,
                            'explanation', v_cur.explanation, 'explanation_en', v_cur.explanation_en, 'figure', v_cur.figure, 'statements', v_cur.statements, 'difficulty', v_cur.difficulty,
                            'figure_checked', coalesce(v_cur.figure_checked, false), 'evidence_target', v_cur.evidence_target, 'evidence_span', v_cur.evidence_span,
                            'answer_rationale', v_cur.answer_rationale, 'distractor_error_types', v_cur.distractor_error_types);
    v_have := (select coalesce(jsonb_object_agg(k, a->k), '{}'::jsonb) from jsonb_object_keys(u->'expect') k);
    v_want := (select coalesce(jsonb_object_agg(k, (a || (u->'set'))->k), '{}'::jsonb) from jsonb_object_keys(u->'expect') k);
    if v_have = v_want then v_skip_p := v_skip_p + 1; raise notice '[%] already applied, skipped', u->>'patch_id'; continue; end if;
    if v_have <> u->'expect' then raise exception '[%] DRIFT: the published version of problem % no longer matches the expected old content (re-run the dry-run)', u->>'patch_id', v_prob.id; end if;
    a := a || (u->'set');
    if exists (select 1 from problem_versions where problem_id = v_prob.id and status in ('draft', 'in_review')) then
      raise exception '[%] problem % has an open draft/in_review version', u->>'patch_id', v_prob.id;
    end if;
    v_new := public.save_problem_draft_version(
      p_problem_id => v_prob.id, p_passage => a->>'passage', p_options => nullif(a->'options', 'null'::jsonb), p_correct_index => (a->>'correct_index')::int,
      p_explanation => a->>'explanation', p_difficulty => a->>'difficulty', p_actor_id => v_actor, p_answers => nullif(a->'answers', 'null'::jsonb),
      p_figure => nullif(a->'figure', 'null'::jsonb), p_figure_checked => coalesce((a->>'figure_checked')::boolean, false), p_statements => nullif(a->'statements', 'null'::jsonb),
      p_question => a->>'question', p_repair_status => null, p_explanation_en => a->>'explanation_en', p_evidence_target => a->>'evidence_target',
      p_evidence_span => a->>'evidence_span', p_answer_rationale => a->>'answer_rationale', p_distractor_error_types => nullif(a->'distractor_error_types', 'null'::jsonb));
    perform public.set_problem_render_check(v_new, u->'render_check');
    perform public.set_problem_quality(v_new, coalesce(v_cur.quality, '{}'::jsonb) || jsonb_build_object('auditFix', u->'audit_fix'));
    perform public.confirm_and_publish_problem_version(v_new, v_actor);
    if u ? 'ap' then perform public.ap_attach_new_version(u->'ap'->>'candidate_key', (u->'ap'->>'item_index')::int, v_new, v_actor); end if;
    v_done_p := v_done_p + 1;
    raise notice '[%] problem % -> new version %', u->>'patch_id', v_prob.id, v_new;
  end loop;

  -- Phase 2: sets -> new set version per affected published set (items of the patched problems point to the new problem versions; snapshots of the rest are copied)
  for s in select * from jsonb_array_elements(v_plan->'sets') loop
    select array_agg(x::uuid) into v_pids from jsonb_array_elements_text(s->'problem_ids') x;
    select * into v_src from mock_exam_sets where set_group_id = (s->>'set_group_id')::uuid and status = 'published' and archived_at is null order by version_no desc limit 1 for update;
    if v_src.id is null then raise exception 'Set group % has no published version (%).', s->>'set_group_id', s->>'name'; end if;
    select count(*) into v_n from mock_exam_set_items i where i.exam_set_id = v_src.id and i.problem_id = any (v_pids);
    if v_n <> cardinality(v_pids) then raise exception 'Set % v% holds % of % target problems.', v_src.name, v_src.version_no, v_n, cardinality(v_pids); end if;
    select count(*) into v_stale from mock_exam_set_items i join problems p on p.id = i.problem_id
     where i.exam_set_id = v_src.id and i.problem_id = any (v_pids) and p.published_version_id is distinct from i.problem_version_id;
    if v_stale = 0 then v_skip_s := v_skip_s + 1; raise notice 'set % v% already up to date, skipped', v_src.name, v_src.version_no; continue; end if;
    perform pg_advisory_xact_lock(hashtextextended('mock_exam_new_version:' || v_src.set_group_id::text, 0));
    if exists (select 1 from mock_exam_sets where set_group_id = v_src.set_group_id and status = 'draft') then
      raise exception 'A draft version already exists for set % - publish or archive it first.', v_src.name;
    end if;
    v_new_set := gen_random_uuid();
    select string_agg(quote_ident(column_name), ', ' order by ordinal_position) into v_cols
      from information_schema.columns where table_schema = 'public' and table_name = 'mock_exam_sets' and is_generated = 'NEVER'
       and column_name not in ('id', 'version_no', 'status', 'created_by', 'created_at', 'published_at', 'published_by', 'archived_at', 'access_tier');
    execute format('insert into mock_exam_sets (id, version_no, status, created_by, access_tier, %s) select $1, $2, ''draft'', $3, ''tutoring'', %s from mock_exam_sets where id = $4', v_cols, v_cols)
      using v_new_set, (select max(version_no) + 1 from mock_exam_sets where set_group_id = v_src.set_group_id), v_actor, v_src.id;
    select string_agg(quote_ident(column_name), ', ' order by ordinal_position),
           string_agg(case column_name
                        when 'problem_version_id' then 'case when i.problem_id = any ($3) then coalesce(p.published_version_id, i.problem_version_id) else i.problem_version_id end'
                        when 'content_snapshot' then 'case when i.problem_id = any ($3) then null else i.content_snapshot end'
                        else 'i.' || quote_ident(column_name) end, ', ' order by ordinal_position)
      into v_cols, v_cols_i
      from information_schema.columns where table_schema = 'public' and table_name = 'mock_exam_set_items' and is_generated = 'NEVER' and column_name not in ('id', 'exam_set_id', 'created_at');
    execute format('insert into mock_exam_set_items (exam_set_id, %s) select $1, %s from mock_exam_set_items i join problems p on p.id = i.problem_id where i.exam_set_id = $2', v_cols, v_cols_i)
      using v_new_set, v_src.id, v_pids;
    if v_src.format = 'mst' and not coalesce((public.mock_exam_validate_mst_set(v_new_set)->>'ready')::boolean, false) then
      raise exception 'New version of % is not ready (4-module blueprint check failed).', v_src.name;
    end if;
    select string_agg(x.problem_id::text || ':' || x.issue, ', ') into v_bad from (select * from public.mock_exam_set_item_issues(v_new_set) where issue is not null limit 5) x;
    if v_bad is not null then raise exception 'New version of % has item issues: %', v_src.name, v_bad; end if;
    perform public.mock_exam_publish_set(v_new_set, v_actor);
    v_done_s := v_done_s + 1;
    raise notice 'set % v% -> v% (%)', v_src.name, v_src.version_no, v_src.version_no + 1, v_new_set;
  end loop;
  raise notice 'DONE problems applied=% skipped=%; sets applied=% skipped=%', v_done_p, v_skip_p, v_done_s, v_skip_s;
end
$audit$;
`;
}

/** 롤백 SQL: 문항은 옛 공개 버전으로 되돌리고(새 버전은 보관), 세트는 새 공개본을 보관하고 이전 공개본을 다시 공개한다. 응시 기록은 exam_set_id 로 그대로. */
export function emitRollbackSql(plan: SqlPlan, prev: { setId: string; setGroupId: string; accessTier: string | null; publishedAt: string | null; publishedBy: string | null }[]): string {
  const rb = { problems: plan.problems.map((p) => ({ patch_id: p.patch_id, problem_id: p.problem_id, from_version_id: p.from_version_id, ...(p.ap ? { ap: p.ap } : {}) })), sets: prev.map((s) => ({ set_id: s.setId, set_group_id: s.setGroupId, access_tier: s.accessTier, published_at: s.publishedAt, published_by: s.publishedBy })) };
  return `${HEADER("External audit fixes 2026-10-13 - ROLLBACK (restore previous published versions)", plan)}
do $audit$
declare
  v_rb constant jsonb := ${jsonLit(rb)};
  v_actor uuid := (select id from profiles where role = 'admin' order by created_at limit 1);
  u jsonb; s jsonb; v_new uuid; v_old problem_versions%rowtype; v_n int := 0;
begin
  -- Problems first (the set publish gate needs each item's version to be the problem's current published version).
  for u in select * from jsonb_array_elements(v_rb->'problems') loop
    select id into v_new from problem_versions where problem_id = (u->>'problem_id')::uuid and status = 'published' and quality->'auditFix'->>'patch' = u->>'patch_id';
    if v_new is null then raise notice '[%] no audit version is published, skipped', u->>'patch_id'; continue; end if;
    select * into v_old from problem_versions where id = (u->>'from_version_id')::uuid;
    if v_old.id is null then raise exception '[%] previous version missing', u->>'patch_id'; end if;
    update problem_versions set status = 'archived' where id = v_new;
    update problem_versions set status = 'published' where id = v_old.id;
    update problems set passage = v_old.passage, options = v_old.options, correct_index = v_old.correct_index, explanation = v_old.explanation, published_version_id = v_old.id where id = v_old.problem_id;
    if u ? 'ap' then perform public.ap_attach_new_version(u->'ap'->>'candidate_key', (u->'ap'->>'item_index')::int, v_old.id, v_actor); end if;
    v_n := v_n + 1;
  end loop;
  -- Sets: archive the version created by the audit, republish the previous one (only when a newer version than the previous exists).
  for s in select * from jsonb_array_elements(v_rb->'sets') loop
    if exists (select 1 from mock_exam_sets n where n.set_group_id = (s->>'set_group_id')::uuid and n.status = 'published' and n.id <> (s->>'set_id')::uuid) then
      update mock_exam_sets set status = 'archived', archived_at = now() where set_group_id = (s->>'set_group_id')::uuid and status = 'published' and id <> (s->>'set_id')::uuid;
      update mock_exam_sets set status = 'published', archived_at = null, published_at = (s->>'published_at')::timestamptz, published_by = (s->>'published_by')::uuid, access_tier = coalesce(s->>'access_tier', access_tier)
       where id = (s->>'set_id')::uuid;
    end if;
  end loop;
  raise notice 'ROLLBACK DONE problems restored=%', v_n;
end
$audit$;
`;
}

/** 적용 후 검증 SELECT(읽기 전용): 새 공개 버전·세트 항목이 현재 공개 버전을 가리키는지. */
export function emitVerifySql(plan: SqlPlan): string {
  const pids = plan.problems.map((p) => `'${p.problem_id}'`).join(", ") || "null";
  const groups = [...new Set(plan.sets.map((s) => `'${s.set_group_id}'`))].join(", ") || "null";
  return `${HEADER("External audit fixes 2026-10-13 - VERIFY (SELECT only)", plan)}
select p.id as problem_id, pv.version_no, pv.status, pv.quality->'auditFix'->>'patch' as patch, (pv.render_check->>'ok') as render_ok
  from problems p join problem_versions pv on pv.id = p.published_version_id where p.id in (${pids}) order by patch;
select s.name, s.version_no, s.status, s.access_tier, s.readiness_status,
       (select count(*) from mock_exam_set_items i where i.exam_set_id = s.id) as items,
       (select count(*) from mock_exam_set_items i join problems p on p.id = i.problem_id where i.exam_set_id = s.id and p.published_version_id is distinct from i.problem_version_id) as stale_items
  from mock_exam_sets s where s.set_group_id in (${groups}) and s.status in ('published', 'draft') order by s.name;
`;
}
